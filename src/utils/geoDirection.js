// Азимут (°, N=0, цагийн зүүний дагуу) → зовхис.
// Кардинал (хойд/зүүн/урд/баруун) 60°, завсрын (зүүн хойд гэх мэт) 30°, нийт 360°.
// зүүн = East, баруун = West (монгол зургийн уламжлал).
export function angleToDirection(deg) {
  const a = ((Number(deg) % 360) + 360) % 360;
  if (a >= 330 || a < 30) return "хойд"; // N   (-30..30)
  if (a < 60) return "зүүн хойд"; // NE  (30..60)
  if (a < 120) return "зүүн"; // E   (60..120)
  if (a < 150) return "зүүн урд"; // SE  (120..150)
  if (a < 210) return "урд"; // S   (150..210)
  if (a < 240) return "баруун урд"; // SW  (210..240)
  if (a < 300) return "баруун"; // W   (240..300)
  return "баруун хойд"; // NW  (300..330)
}
