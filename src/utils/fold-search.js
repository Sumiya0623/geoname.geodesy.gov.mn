// ----------------------------------------------------------------------
// Хайлтын норматив (латин/кирилл хольц).
//
// Нэрлэвэрийн код (ж: "M-47-73-B-б-2") нь ЛАТИН (M, B) ба КИРИЛЛ (А, Б, в)
// үсэг холилдож хадгалагдсан байдаг тул монгол гараас бичсэн "М-47-73"
// (кирилл М) шууд тааралддаггүй. Иймд ижил дүрстэй үсгүүдийг нэг ангилалд
// буулгаж, зураас/зай зэрэг тусгаарлагчийг хаяад харьцуулна.
//
// Б, В, латин B — гурвуулаа нэг ангилалд: өгөгдөлд "В"-г латин B-гээр бичсэн
// тохиолдол олон тул ялгавал хайлт мултарна (нарийвчлалаас илүү бүрэн олохыг
// чухалчлав).
// ----------------------------------------------------------------------

const FOLD_MAP = {
  а: "a",
  б: "b",
  в: "b",
  b: "b",
  г: "g",
  е: "e",
  ё: "e",
  к: "k",
  л: "l",
  м: "m",
  н: "n",
  о: "o",
  р: "p",
  с: "c",
  т: "t",
  у: "y",
  х: "x",
};

export const fold = (v) =>
  String(v ?? "")
    .toLowerCase()
    .replace(/[^0-9a-zа-яё]+/g, "")
    .replace(/[а-яёb]/g, (ch) => FOLD_MAP[ch] ?? ch);

export default fold;
